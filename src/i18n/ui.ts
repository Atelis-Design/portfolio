const UI: Record<Locale, UiStrings> = { tr, en, de, fr, es, it, ru };

export function useUi(locale: Locale): UiStrings {
  return UI[locale];
}

/** Replace `{name}` tokens: format('{a} of {b}', { a: 1, b: 2 }). */
export function format(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}

/** Tiny subset used by the static 404 page to localize itself client-side. */
export function notFoundStrings() {
  return Object.fromEntries(
    Object.entries(UI).map(([locale, ui]) => [locale, { ...ui.notFound, home: ui.nav.home }]),
  ) as Record<Locale, UiStrings['notFound'] & { home: string }>;
}
